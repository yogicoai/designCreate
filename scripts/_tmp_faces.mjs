import { MongoClient } from 'mongodb';
const c = await new MongoClient(process.env.MONGODB_URI).connect();
const db = c.db(process.env.MONGODB_DB);
const since = new Date(Date.now() - 12 * 864e5);
const q = { createdAt: { $gte: since }, provider: { $in: ['gemini', 'gpt'] } };
const one = await db.collection('cuts').findOne({ ...q, 'qc.face': { $exists: true } }, { sort: { createdAt: -1 } });
console.log('KEYS', Object.keys(one || {}).join(' '));
console.log('qc.face sample', JSON.stringify(one?.qc?.face).slice(0, 400));
console.log('talent fields', JSON.stringify({ talents: one?.talents, talentCodes: one?.talentCodes, models: one?.models }).slice(0, 300));
console.log('total recent', await db.collection('cuts').countDocuments(q));
await c.close();
